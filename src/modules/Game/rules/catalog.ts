const slot = (n: number) => String(n).padStart(2, '0')

export interface CatalogRandom {
  next: () => number
  nextId: () => number
}

export function shuffle<T>(items: T[], random: CatalogRandom): T[] {
  const result = items.slice()
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(random.next() * (i + 1))
    ;[result[i], result[j]] = [result[j], result[i]]
  }
  return result
}

export function makePlayers(random: CatalogRandom): PlayerCard[] {
  const players: PlayerCard[] = []
  for (const el of ELS) {
    const rarities = shuffle(RARITY_SPLIT, random)
    PLAYERS[el].forEach(([name, perk, strengths], i) => {
      const rar = rarities[i]
      players.push({
        id: random.nextId(),
        kind: 'player',
        el,
        name,
        str: strengths[RARITY_INDEX[rar]],
        rar,
        perk,
        art: `${CARDS_URL}/player/${RARITY_FOLDER[rar]}/${slot(ELEMENT_OFFSET[el] + i + 1)}.webp`,
      })
    })
  }
  return shuffle(players, random)
}

export function makeTrainers(random: CatalogRandom): TrainerCard[] {
  return TRAINERS.map(([el, name], i) => ({
    id: random.nextId(),
    kind: 'trainer',
    el,
    name,
    coef: 1.5,
    perk: 'x1.5 игрокам со стихией ' + { morality: 'Мораль', erudition: 'Эрудиция', luck: 'Удача' }[el],
    art: `${CARDS_URL}/trainer/${slot(i + 1)}.webp`,
  }))
}

export function makeEffects(random: CatalogRandom): EffectCard[] {
  return shuffle(
    EFFECTS.map(([kind, el, name, val, perk], i) => ({
      id: random.nextId(),
      kind,
      el,
      name,
      val,
      perk,
      art: `${CARDS_URL}/effect/${slot(i + 1)}.webp`,
    })),
    random,
  )
}

export function perkText(card: EffectCard): string {
  return card.perk
}
